CREATE TABLE IF NOT EXISTS sources (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_key TEXT UNIQUE NOT NULL, kind TEXT NOT NULL,
 title TEXT NOT NULL, url TEXT NOT NULL DEFAULT '',
 groups JSONB NOT NULL DEFAULT '[]', audiences JSONB NOT NULL DEFAULT '[]',
 for_br BOOLEAN NOT NULL DEFAULT false, for_info BOOLEAN NOT NULL DEFAULT false,
 enabled BOOLEAN NOT NULL DEFAULT true, audience_origin TEXT NOT NULL DEFAULT 'unassigned'
);
CREATE TABLE IF NOT EXISTS source_endpoints (
 endpoint TEXT PRIMARY KEY, source_id BIGINT NOT NULL REFERENCES sources(id),
 kind TEXT NOT NULL CHECK(kind IN ('telegram','rss','web')),
 enabled BOOLEAN NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS source_health (
 endpoint TEXT PRIMARY KEY REFERENCES source_endpoints(endpoint) ON DELETE CASCADE,
 checked_at TIMESTAMPTZ NOT NULL DEFAULT now(), check_ok BOOLEAN NOT NULL DEFAULT false,
 remote_item_at TIMESTAMPTZ, remote_item_key TEXT NOT NULL DEFAULT '',
 missing_count INTEGER NOT NULL DEFAULT 0, error TEXT NOT NULL DEFAULT '',
 details JSONB NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS idx_source_health_checked ON source_health(checked_at);
