-- Three-role workflow: collector writes candidates, editor alone publishes.
CREATE TABLE IF NOT EXISTS note_drafts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_document_id BIGINT REFERENCES source_documents(id) ON DELETE SET NULL,
 source_kind TEXT NOT NULL, source_chat_id BIGINT NOT NULL, source_message_id BIGINT NOT NULL,
 source_title TEXT NOT NULL, source_url TEXT NOT NULL DEFAULT '',
 content_hash TEXT NOT NULL, analysis JSONB NOT NULL,
 suggested_action TEXT NOT NULL CHECK(suggested_action IN ('new','update')),
 target_news_id BIGINT REFERENCES news(id),
 status TEXT NOT NULL DEFAULT 'queued' CHECK(status IN ('queued','processing','published','duplicate','rejected','manual_review','failed')),
 attempts INTEGER NOT NULL DEFAULT 0, error TEXT NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), locked_at TIMESTAMPTZ,
 completed_at TIMESTAMPTZ, UNIQUE(source_kind,source_chat_id,source_message_id,content_hash)
);
CREATE INDEX IF NOT EXISTS idx_note_drafts_queue ON note_drafts(status,created_at);
CREATE TABLE IF NOT EXISTS editorial_decisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 draft_id BIGINT NOT NULL REFERENCES note_drafts(id) ON DELETE CASCADE,
 action TEXT NOT NULL, target_news_id BIGINT REFERENCES news(id), result_news_id BIGINT REFERENCES news(id),
 model TEXT NOT NULL, reviewed_analysis JSONB NOT NULL DEFAULT '{}', reason TEXT NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Calendar cards are independent from notes and retain all date revisions.
CREATE TABLE IF NOT EXISTS calendar_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 canonical_key TEXT UNIQUE NOT NULL, title TEXT NOT NULL, summary TEXT NOT NULL DEFAULT '',
 starts_at TIMESTAMPTZ, ends_at TIMESTAMPTZ, all_day BOOLEAN NOT NULL DEFAULT false,
 date_precision TEXT NOT NULL DEFAULT 'unknown' CHECK(date_precision IN ('exact','day','month','range','approximate','unknown')),
 timezone TEXT NOT NULL DEFAULT 'Europe/Kyiv',
 status TEXT NOT NULL DEFAULT 'tentative' CHECK(status IN ('tentative','confirmed','postponed','cancelled','completed')),
 location TEXT NOT NULL DEFAULT '', participants JSONB NOT NULL DEFAULT '[]',
 audiences JSONB NOT NULL DEFAULT '[]', tags JSONB NOT NULL DEFAULT '[]', confidence INTEGER NOT NULL DEFAULT 0,
 first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(), last_verified_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_calendar_events_dates ON calendar_events(starts_at,ends_at,status);
CREATE INDEX IF NOT EXISTS idx_calendar_events_search ON calendar_events USING GIN(
 to_tsvector('simple',coalesce(title,'')||' '||coalesce(summary,'')||' '||coalesce(location,''))
);
CREATE TABLE IF NOT EXISTS event_candidates (
