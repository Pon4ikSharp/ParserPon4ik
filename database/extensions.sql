 source_url TEXT NOT NULL DEFAULT '', observed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 evidence JSONB NOT NULL DEFAULT '{}', PRIMARY KEY(event_id,source_url)
);
CREATE TABLE IF NOT EXISTS calendar_event_revisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id BIGINT NOT NULL REFERENCES calendar_events(id) ON DELETE CASCADE,
 revision_no INTEGER NOT NULL, snapshot JSONB NOT NULL, changed_fields JSONB NOT NULL DEFAULT '[]',
