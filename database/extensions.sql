 source_document_id BIGINT REFERENCES source_documents(id) ON DELETE SET NULL,
 note_draft_id BIGINT REFERENCES note_drafts(id) ON DELETE SET NULL,
 candidate_key TEXT NOT NULL, candidate_text TEXT NOT NULL, payload JSONB NOT NULL DEFAULT '{}',
 status TEXT NOT NULL DEFAULT 'queued' CHECK(status IN ('queued','processing','confirmed','merged','rejected','manual_review','failed')),
 attempts INTEGER NOT NULL DEFAULT 0, error TEXT NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), locked_at TIMESTAMPTZ, completed_at TIMESTAMPTZ,
 UNIQUE(source_document_id,candidate_key)
);
CREATE INDEX IF NOT EXISTS idx_event_candidates_queue ON event_candidates(status,created_at);
CREATE TABLE IF NOT EXISTS calendar_event_sources (
 event_id BIGINT NOT NULL REFERENCES calendar_events(id) ON DELETE CASCADE,
