CREATE OR REPLACE VIEW originals_search AS
 SELECT d.id,d.published_at,d.source_title,d.source_url,d.source_text,d.full_text,
 d.feed_text,d.raw_html,d.content_status,d.metadata,s.groups,s.audiences,
 s.for_br,s.for_info,i.status AS influence_status,i.role,i.narrative_title,
 i.claims::jsonb AS claims,i.techniques::jsonb AS techniques,
 i.strategic_objectives::jsonb AS strategic_objectives
 FROM source_documents d LEFT JOIN sources s ON s.id=d.source_id
 LEFT JOIN info_influence i ON i.source_document_id=d.id;
