-- Processing Engine v2
--
-- Additive-only schema. It deliberately does not ALTER/DELETE/UPDATE any
-- legacy ingestion, classification, editorial, or delivery table.
--
-- source_documents remains the immutable input archive for v2.

CREATE TABLE IF NOT EXISTS processing_v2_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_document_id BIGINT NOT NULL
        REFERENCES source_documents(id) ON DELETE CASCADE,
    pipeline_version TEXT NOT NULL,
    source_hash TEXT NOT NULL,
    stage TEXT NOT NULL
        CHECK (stage IN ('prefilter', 'hydrate', 'analyze')),
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN (
            'pending',
            'processing',
            'retry',
            'completed',
            'skipped',
            'dead_letter'
        )),
    priority INTEGER NOT NULL DEFAULT 100,
    attempts INTEGER NOT NULL DEFAULT 0,
    max_attempts INTEGER NOT NULL DEFAULT 3,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    locked_at TIMESTAMPTZ,
    locked_by TEXT NOT NULL DEFAULT '',
    last_error TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ,
    UNIQUE (source_document_id, pipeline_version, source_hash, stage)
);

CREATE INDEX IF NOT EXISTS idx_processing_v2_jobs_claim
    ON processing_v2_jobs (
        pipeline_version,
        stage,
        status,
        next_attempt_at,
        priority,
        created_at,
        id
    )
    WHERE status IN ('pending', 'retry');

CREATE INDEX IF NOT EXISTS idx_processing_v2_jobs_document
    ON processing_v2_jobs (source_document_id, pipeline_version, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_processing_v2_jobs_locked
    ON processing_v2_jobs (locked_at)
    WHERE status = 'processing';


CREATE TABLE IF NOT EXISTS processing_v2_prefilter_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_document_id BIGINT NOT NULL
        REFERENCES source_documents(id) ON DELETE CASCADE,
    pipeline_version TEXT NOT NULL,
    source_hash TEXT NOT NULL,
    decision TEXT NOT NULL
        CHECK (decision IN ('pass', 'drop', 'duplicate_exact', 'duplicate_near')),
    reason TEXT NOT NULL,
    input_basis TEXT NOT NULL
        CHECK (input_basis IN ('source_text', 'feed_text', 'full_text', 'manual')),
    char_count INTEGER NOT NULL DEFAULT 0,
    word_count INTEGER NOT NULL DEFAULT 0,
    url_count INTEGER NOT NULL DEFAULT 0,
    exact_key TEXT NOT NULL DEFAULT '',
    fingerprint64 TEXT NOT NULL DEFAULT '',
    canonical_document_id BIGINT
        REFERENCES source_documents(id) ON DELETE SET NULL,
    similarity NUMERIC(6,5),
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (source_document_id, pipeline_version, source_hash)
);

CREATE INDEX IF NOT EXISTS idx_processing_v2_prefilter_decision
    ON processing_v2_prefilter_results (pipeline_version, decision, created_at);

CREATE INDEX IF NOT EXISTS idx_processing_v2_prefilter_exact
    ON processing_v2_prefilter_results (pipeline_version, exact_key)
    WHERE exact_key <> '';

CREATE INDEX IF NOT EXISTS idx_processing_v2_prefilter_fingerprint
    ON processing_v2_prefilter_results (pipeline_version, fingerprint64)
    WHERE fingerprint64 <> '';


CREATE TABLE IF NOT EXISTS processing_v2_job_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL
        REFERENCES processing_v2_jobs(id) ON DELETE CASCADE,
    from_status TEXT NOT NULL DEFAULT '',
    to_status TEXT NOT NULL,
    worker TEXT NOT NULL DEFAULT '',
    attempt INTEGER NOT NULL DEFAULT 0,
    detail JSONB NOT NULL DEFAULT '{}'::jsonb,
    error TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_processing_v2_job_events_job
    ON processing_v2_job_events (job_id, created_at, id);


CREATE TABLE IF NOT EXISTS processing_v2_hydration_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_document_id BIGINT NOT NULL
        REFERENCES source_documents(id) ON DELETE CASCADE,
    pipeline_version TEXT NOT NULL,
    source_hash TEXT NOT NULL,
    requested_url TEXT NOT NULL,
    final_url TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL
        CHECK (status IN ('extracted', 'partial', 'paywall', 'blocked', 'error')),
    full_text TEXT NOT NULL DEFAULT '',
    raw_html TEXT NOT NULL DEFAULT '',
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    error TEXT NOT NULL DEFAULT '',
    used_proxy BOOLEAN NOT NULL DEFAULT false,
    duration_ms BIGINT NOT NULL DEFAULT 0,
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (source_document_id, pipeline_version, source_hash)
);

CREATE INDEX IF NOT EXISTS idx_processing_v2_hydration_status
    ON processing_v2_hydration_results (pipeline_version, status, fetched_at);

CREATE INDEX IF NOT EXISTS idx_processing_v2_hydration_document
    ON processing_v2_hydration_results (
        source_document_id,
        pipeline_version,
        created_at DESC
    );


CREATE TABLE IF NOT EXISTS processing_v2_run_guards (
    run_key TEXT PRIMARY KEY,
    purpose TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_processing_v2_run_guards_created
    ON processing_v2_run_guards (created_at DESC);


CREATE TABLE IF NOT EXISTS processing_v2_ai_calls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_version TEXT NOT NULL,
    stage TEXT NOT NULL,
    model TEXT NOT NULL,
    reasoning_effort TEXT NOT NULL DEFAULT '',
    verbosity TEXT NOT NULL DEFAULT '',
    document_count INTEGER NOT NULL DEFAULT 0,
    input_chars BIGINT NOT NULL DEFAULT 0,
    output_chars BIGINT NOT NULL DEFAULT 0,
    input_tokens BIGINT,
    cached_input_tokens BIGINT,
    output_tokens BIGINT,
    duration_ms BIGINT NOT NULL DEFAULT 0,
    success BOOLEAN NOT NULL DEFAULT false,
    error TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_processing_v2_ai_calls_pipeline
    ON processing_v2_ai_calls (pipeline_version, stage, created_at DESC);


CREATE TABLE IF NOT EXISTS processing_v2_document_analysis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_document_id BIGINT NOT NULL
        REFERENCES source_documents(id) ON DELETE CASCADE,
    pipeline_version TEXT NOT NULL,
    source_hash TEXT NOT NULL,

    input_basis TEXT NOT NULL
        CHECK (input_basis IN (
            'source_text',
            'feed_text',
            'full_text',
            'manual',
            'hydration_v2',
            'hydration_v2_partial'
        )),
    input_chars INTEGER NOT NULL DEFAULT 0,

    language TEXT NOT NULL DEFAULT '',
    summary TEXT NOT NULL DEFAULT '',

    briefing_relevant BOOLEAN,
    briefing_score SMALLINT
        CHECK (briefing_score IS NULL OR briefing_score BETWEEN 0 AND 100),

    influence_relevant BOOLEAN,
    influence_score SMALLINT
        CHECK (influence_score IS NULL OR influence_score BETWEEN 0 AND 100),

    event_relevant BOOLEAN,
    event_score SMALLINT
        CHECK (event_score IS NULL OR event_score BETWEEN 0 AND 100),

    entities JSONB NOT NULL DEFAULT '[]'::jsonb,
    topics JSONB NOT NULL DEFAULT '[]'::jsonb,
    event_data JSONB NOT NULL DEFAULT '{}'::jsonb,
    influence_data JSONB NOT NULL DEFAULT '{}'::jsonb,
    briefing_data JSONB NOT NULL DEFAULT '{}'::jsonb,

    result JSONB NOT NULL DEFAULT '{}'::jsonb,
    quality JSONB NOT NULL DEFAULT '{}'::jsonb,

    model TEXT NOT NULL DEFAULT '',
    prompt_version TEXT NOT NULL DEFAULT '',
    duration_ms BIGINT NOT NULL DEFAULT 0,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    UNIQUE (source_document_id, pipeline_version, source_hash)
);

CREATE INDEX IF NOT EXISTS idx_processing_v2_analysis_document
    ON processing_v2_document_analysis (
        source_document_id,
        pipeline_version,
        created_at DESC
    );

CREATE INDEX IF NOT EXISTS idx_processing_v2_analysis_briefing
    ON processing_v2_document_analysis (briefing_relevant, briefing_score DESC)
    WHERE briefing_relevant IS TRUE;

CREATE INDEX IF NOT EXISTS idx_processing_v2_analysis_influence
    ON processing_v2_document_analysis (influence_relevant, influence_score DESC)
    WHERE influence_relevant IS TRUE;

CREATE INDEX IF NOT EXISTS idx_processing_v2_analysis_event
    ON processing_v2_document_analysis (event_relevant, event_score DESC)
    WHERE event_relevant IS TRUE;

CREATE INDEX IF NOT EXISTS idx_processing_v2_analysis_entities
    ON processing_v2_document_analysis USING GIN (entities);

CREATE INDEX IF NOT EXISTS idx_processing_v2_analysis_topics
    ON processing_v2_document_analysis USING GIN (topics);


CREATE OR REPLACE VIEW processing_v2_queue_overview AS
SELECT
    pipeline_version,
    stage,
    status,
    count(*) AS jobs,
    min(created_at) AS oldest_created_at,
    min(next_attempt_at)
        FILTER (WHERE status IN ('pending', 'retry')) AS next_ready_at,
    count(*) FILTER (
        WHERE status = 'processing'
          AND locked_at < now() - interval '30 minutes'
    ) AS stale_processing
FROM processing_v2_jobs
GROUP BY pipeline_version, stage, status;
