-- Grok Analysis v1: isolated semantic analysis layer.
-- Does not modify raw source_documents or legacy processing tables.

CREATE TABLE IF NOT EXISTS grok_document_analysis_v1 (
  source_document_id BIGINT PRIMARY KEY REFERENCES source_documents(id) ON DELETE CASCADE,
  relevant BOOLEAN NOT NULL,
  keep_for_analysis BOOLEAN NOT NULL,
  priority TEXT NOT NULL CHECK(priority IN ('low','medium','high')),
  speaker TEXT NOT NULL DEFAULT '',
  speaker_role TEXT NOT NULL DEFAULT 'none'
    CHECK(speaker_role IN ('speaker','quoted','mentioned','addressee','future_speaker','editorial','none')),
  mentioned_actors JSONB NOT NULL DEFAULT '[]'::jsonb,
  main_claim TEXT NOT NULL DEFAULT '',
  narratives JSONB NOT NULL DEFAULT '[]'::jsonb,
  target_audiences JSONB NOT NULL DEFAULT '[]'::jsonb,
  influence_methods JSONB NOT NULL DEFAULT '[]'::jsonb,
  likely_objectives JSONB NOT NULL DEFAULT '[]'::jsonb,
  source_role TEXT NOT NULL DEFAULT 'unclear'
    CHECK(source_role IN ('originator','official','relay','commentary','aggregator','unclear')),
  novelty TEXT NOT NULL DEFAULT 'new'
    CHECK(novelty IN ('new','development','duplicate')),
  story_key TEXT NOT NULL DEFAULT '',
  duplicate_of_document_id BIGINT REFERENCES source_documents(id) ON DELETE SET NULL,
  added_value TEXT NOT NULL DEFAULT '',
  confidence SMALLINT NOT NULL DEFAULT 0 CHECK(confidence BETWEEN 0 AND 100),
  reason TEXT NOT NULL DEFAULT '',
  model TEXT NOT NULL DEFAULT 'grok-bot',
  prompt_version TEXT NOT NULL DEFAULT 'grok-analysis-v1',
  run_id TEXT NOT NULL DEFAULT '',
  raw_result JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK(duplicate_of_document_id IS NULL OR duplicate_of_document_id <> source_document_id)
);

CREATE INDEX IF NOT EXISTS idx_grok_analysis_relevant
  ON grok_document_analysis_v1(relevant,keep_for_analysis,priority,updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_grok_analysis_story_key
  ON grok_document_analysis_v1(story_key) WHERE story_key <> '';

CREATE TABLE IF NOT EXISTS grok_stories_v1 (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  story_key TEXT UNIQUE NOT NULL,
  canonical_document_id BIGINT REFERENCES source_documents(id) ON DELETE SET NULL,
  title TEXT NOT NULL DEFAULT '',
  summary TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'active'
    CHECK(status IN ('active','closed','merged')),
  narrative_keys JSONB NOT NULL DEFAULT '[]'::jsonb,
  target_audiences JSONB NOT NULL DEFAULT '[]'::jsonb,
  likely_objectives JSONB NOT NULL DEFAULT '[]'::jsonb,
  first_seen_at TIMESTAMPTZ,
  last_seen_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_grok_stories_last_seen
  ON grok_stories_v1(status,last_seen_at DESC);

CREATE TABLE IF NOT EXISTS grok_story_members_v1 (
  story_id BIGINT NOT NULL REFERENCES grok_stories_v1(id) ON DELETE CASCADE,
  source_document_id BIGINT NOT NULL UNIQUE REFERENCES source_documents(id) ON DELETE CASCADE,
  relation TEXT NOT NULL
    CHECK(relation IN ('canonical','duplicate','development')),
  added_value TEXT NOT NULL DEFAULT '',
  attached_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY(story_id,source_document_id)
);

CREATE INDEX IF NOT EXISTS idx_grok_story_members_story
  ON grok_story_members_v1(story_id,relation,attached_at);

CREATE TABLE IF NOT EXISTS grok_analysis_audit_v1 (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_document_id BIGINT REFERENCES source_documents(id) ON DELETE SET NULL,
  action TEXT NOT NULL,
  payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_grok_analysis_audit_doc
  ON grok_analysis_audit_v1(source_document_id,created_at DESC);


