-- Grok semantic memory v1: Narrative -> Thesis -> Story.

CREATE TABLE IF NOT EXISTS grok_narratives_v1 (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  narrative_key TEXT NOT NULL UNIQUE,
  label TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'active'
    CHECK(status IN ('active','inactive','merged')),
  confidence SMALLINT NOT NULL DEFAULT 0 CHECK(confidence BETWEEN 0 AND 100),
  first_seen_at TIMESTAMPTZ,
  last_seen_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS grok_theses_v1 (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thesis_key TEXT NOT NULL UNIQUE,
  label TEXT NOT NULL,
  thesis TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'active'
    CHECK(status IN ('active','inactive','merged')),
  confidence SMALLINT NOT NULL DEFAULT 0 CHECK(confidence BETWEEN 0 AND 100),
  first_seen_at TIMESTAMPTZ,
  last_seen_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS grok_narrative_theses_v1 (
  narrative_id BIGINT NOT NULL REFERENCES grok_narratives_v1(id) ON DELETE CASCADE,
  thesis_id BIGINT NOT NULL REFERENCES grok_theses_v1(id) ON DELETE CASCADE,
  confidence SMALLINT NOT NULL DEFAULT 0 CHECK(confidence BETWEEN 0 AND 100),
  linked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY(narrative_id,thesis_id)
);

CREATE TABLE IF NOT EXISTS grok_story_theses_v1 (
  story_id BIGINT NOT NULL REFERENCES grok_stories_v1(id) ON DELETE CASCADE,
  thesis_id BIGINT NOT NULL REFERENCES grok_theses_v1(id) ON DELETE CASCADE,
  relation TEXT NOT NULL DEFAULT 'primary'
    CHECK(relation IN ('primary','secondary')),
  confidence SMALLINT NOT NULL DEFAULT 0 CHECK(confidence BETWEEN 0 AND 100),
  linked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY(story_id,thesis_id)
);

CREATE INDEX IF NOT EXISTS idx_grok_narratives_active
  ON grok_narratives_v1(status,last_seen_at DESC);
CREATE INDEX IF NOT EXISTS idx_grok_theses_active
  ON grok_theses_v1(status,last_seen_at DESC);
CREATE INDEX IF NOT EXISTS idx_grok_story_theses_thesis
  ON grok_story_theses_v1(thesis_id,story_id);

ALTER TABLE grok_analysis_run_items_v1
  ADD COLUMN IF NOT EXISTS semantic_status TEXT NOT NULL DEFAULT 'pending';

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conname='grok_run_items_semantic_status_check'
  ) THEN
    ALTER TABLE grok_analysis_run_items_v1
      ADD CONSTRAINT grok_run_items_semantic_status_check
      CHECK(semantic_status IN ('pending','done','skipped'));
  END IF;
END $$;

UPDATE grok_analysis_run_items_v1 ri
   SET semantic_status='skipped'
  FROM grok_analysis_runs_v1 r
 WHERE r.run_key=ri.run_key
   AND r.status='completed'
   AND ri.semantic_status='pending';

CREATE UNIQUE INDEX IF NOT EXISTS uq_grok_story_primary_thesis
  ON grok_story_theses_v1(story_id)
  WHERE relation='primary';
