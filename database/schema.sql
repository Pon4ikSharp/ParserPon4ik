CREATE TABLE messages (
            chat_id BIGINT NOT NULL,
            message_id BIGINT NOT NULL,
            content_hash TEXT NOT NULL,
            source_title TEXT NOT NULL,
            source_url TEXT NOT NULL,
            status TEXT NOT NULL,
            reason TEXT NOT NULL,
            created_at TEXT NOT NULL,
            PRIMARY KEY (chat_id, message_id)
        );

CREATE TABLE news (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            chat_id BIGINT NOT NULL,
            message_id BIGINT NOT NULL,
            category TEXT NOT NULL,
            paragraph TEXT NOT NULL,
            reference_text TEXT NOT NULL DEFAULT '',
            event_key TEXT NOT NULL,
            facts_key TEXT NOT NULL,
            article_key TEXT NOT NULL DEFAULT '',
            primary_sources TEXT NOT NULL DEFAULT '[]',
            source_title TEXT NOT NULL,
            source_url TEXT NOT NULL,
            source_links TEXT NOT NULL DEFAULT '[]',
            canonical_id BIGINT,
            supersedes_id BIGINT,
            is_current BIGINT NOT NULL DEFAULT 1,
            created_at TEXT NOT NULL,
            updated_at TEXT,
            UNIQUE(chat_id, message_id)
        );

CREATE TABLE subscribers (
            chat_id BIGINT PRIMARY KEY,
            username TEXT NOT NULL,
            display_name TEXT NOT NULL,
            is_active BIGINT NOT NULL DEFAULT 1,
            subscribed_at TEXT NOT NULL,
            updated_at TEXT NOT NULL
        );

CREATE TABLE detected_events (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            event_key TEXT NOT NULL UNIQUE,
            event_text TEXT NOT NULL,
            source_title TEXT NOT NULL,
            source_url TEXT NOT NULL,
            created_at TEXT NOT NULL
        );

CREATE TABLE digest_runs (
            window_end TEXT PRIMARY KEY,
            window_start TEXT NOT NULL,
            filename TEXT NOT NULL,
            item_count BIGINT NOT NULL,
            created_at TEXT NOT NULL
        );

CREATE TABLE rss_entries (
            entry_key TEXT PRIMARY KEY,
            feed_url TEXT NOT NULL,
            entry_url TEXT NOT NULL,
            title TEXT NOT NULL,
            published_at TEXT,
            status TEXT NOT NULL,
            reason TEXT NOT NULL,
            created_at TEXT NOT NULL
        );

CREATE TABLE rss_feed_state (
            feed_url TEXT PRIMARY KEY,
            source_title TEXT NOT NULL,
            initialized_at TEXT NOT NULL,
            last_checked_at TEXT NOT NULL,
            last_error TEXT NOT NULL
        );

CREATE TABLE source_documents (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            source_kind TEXT NOT NULL,
            source_chat_id BIGINT NOT NULL,
            source_message_id BIGINT NOT NULL,
            feed_url TEXT NOT NULL DEFAULT '',
            content_hash TEXT NOT NULL,
            source_title TEXT NOT NULL,
            source_url TEXT NOT NULL,
            source_text TEXT NOT NULL,
            published_at TEXT,
            created_at TEXT NOT NULL,
            updated_at TEXT NOT NULL,
            UNIQUE(source_kind, source_chat_id, source_message_id)
        );

CREATE TABLE info_influence (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            source_document_id BIGINT,
            source_kind TEXT NOT NULL,
            source_chat_id BIGINT NOT NULL,
            source_message_id BIGINT NOT NULL,
            content_hash TEXT NOT NULL,
            source_title TEXT NOT NULL,
            source_url TEXT NOT NULL,
            role TEXT NOT NULL,
            narrative_title TEXT NOT NULL,
            summary TEXT NOT NULL,
            target_entities TEXT NOT NULL DEFAULT '[]',
            techniques TEXT NOT NULL DEFAULT '[]',
            claims TEXT NOT NULL DEFAULT '[]',
            strategic_objectives TEXT NOT NULL DEFAULT '[]',
            audiences TEXT NOT NULL DEFAULT '[]',
            actors TEXT NOT NULL DEFAULT '[]',
            information_triggers TEXT NOT NULL DEFAULT '[]',
            future_relevance TEXT NOT NULL DEFAULT '',
            confidence BIGINT NOT NULL DEFAULT 0,
            narrative_key TEXT NOT NULL,
            classifier_version TEXT NOT NULL DEFAULT '',
            status TEXT NOT NULL,
            reason TEXT NOT NULL,
            created_at TEXT NOT NULL,
            updated_at TEXT,
            UNIQUE(source_kind, source_chat_id, source_message_id)
        );

CREATE TABLE system_state (
            key TEXT PRIMARY KEY,
            value TEXT NOT NULL,
            updated_at TEXT NOT NULL
        );

CREATE INDEX idx_messages_hash ON messages(content_hash);

CREATE INDEX idx_news_created_at ON news(created_at);

CREATE INDEX idx_news_current_window ON news(is_current, created_at, updated_at);

CREATE INDEX idx_source_documents_published_at ON source_documents(published_at);

CREATE INDEX idx_source_documents_hash ON source_documents(content_hash);

CREATE INDEX idx_source_documents_source ON source_documents(source_kind, source_title);

CREATE INDEX idx_info_influence_created_at ON info_influence(created_at);

CREATE INDEX idx_info_influence_narrative_key ON info_influence(narrative_key);

CREATE INDEX idx_info_influence_hash ON info_influence(content_hash);

