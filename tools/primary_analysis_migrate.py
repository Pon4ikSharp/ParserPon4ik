"""Idempotent v6.3 SAFE schema migration for primary-analysis dedup and telemetry."""
from __future__ import annotations
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.db import connect
from app import primary_dedup

SQL = r'''
CREATE TABLE IF NOT EXISTS primary_dedup_links (
    duplicate_document_id BIGINT PRIMARY KEY REFERENCES source_documents(id) ON DELETE CASCADE,
    canonical_document_id BIGINT NOT NULL REFERENCES source_documents(id) ON DELETE CASCADE,
    cluster_id BIGINT NOT NULL REFERENCES source_documents(id) ON DELETE CASCADE,
    duplicate_type TEXT NOT NULL CHECK(duplicate_type IN ('exact','near')),
    similarity DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    normalized_hash TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_primary_dedup_canonical ON primary_dedup_links(canonical_document_id);
CREATE INDEX IF NOT EXISTS idx_primary_dedup_cluster ON primary_dedup_links(cluster_id);
CREATE INDEX IF NOT EXISTS idx_primary_dedup_created ON primary_dedup_links(created_at);
CREATE INDEX IF NOT EXISTS idx_primary_dedup_hash ON primary_dedup_links(normalized_hash);

CREATE TABLE IF NOT EXISTS primary_worker_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type TEXT NOT NULL,
    source_document_id BIGINT REFERENCES source_documents(id) ON DELETE SET NULL,
    worker_id INTEGER,
    detail TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_primary_worker_events_time ON primary_worker_events(created_at,event_type);

CREATE TABLE IF NOT EXISTS primary_worker_state (
    worker_id INTEGER PRIMARY KEY,
    label TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'stopped',
    current_document_id BIGINT REFERENCES source_documents(id) ON DELETE SET NULL,
    started_at TIMESTAMPTZ,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_primary_worker_state_seen ON primary_worker_state(status,last_seen_at);

CREATE TABLE IF NOT EXISTS rss_ingest_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL REFERENCES sources(id) ON DELETE CASCADE,
    source_document_id BIGINT NOT NULL REFERENCES source_documents(id) ON DELETE CASCADE,
    canonical_url TEXT NOT NULL DEFAULT '',
    normalized_hash TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- v6.3 SAFE: only same source + canonical URL can suppress RSS ingest.
DROP INDEX IF EXISTS uq_rss_ingest_source_hash;
CREATE UNIQUE INDEX IF NOT EXISTS uq_rss_ingest_source_url
    ON rss_ingest_keys(source_id,canonical_url) WHERE canonical_url<>'';
CREATE INDEX IF NOT EXISTS idx_rss_ingest_document ON rss_ingest_keys(source_document_id);

CREATE OR REPLACE VIEW primary_story_clusters AS
WITH cluster_docs AS (
    SELECT cluster_id, canonical_document_id, canonical_document_id AS document_id
      FROM primary_dedup_links
    UNION
    SELECT cluster_id, canonical_document_id, duplicate_document_id AS document_id
      FROM primary_dedup_links
)
SELECT cd.cluster_id,
       cd.canonical_document_id,
       max(i.narrative_title) AS narrative_title,
       count(DISTINCT cd.document_id) AS publications,
       GREATEST(count(DISTINCT cd.document_id)-1,0) AS retransmissions,
       count(DISTINCT d.source_id) AS source_count,
       array_agg(DISTINCT d.source_title) AS sources,
       min(COALESCE(NULLIF(d.published_at,'')::timestamptz,NULLIF(d.created_at,'')::timestamptz)) AS first_seen_at,
       max(COALESCE(NULLIF(d.published_at,'')::timestamptz,NULLIF(d.created_at,'')::timestamptz)) AS last_seen_at
  FROM cluster_docs cd
  JOIN source_documents d ON d.id=cd.document_id
  LEFT JOIN info_influence i ON i.source_document_id=cd.canonical_document_id
 GROUP BY cd.cluster_id,cd.canonical_document_id;
'''


def sanitize_legacy_ingest_keys(database) -> tuple[int, int]:
    """Disable the unsafe v6.2 hash key without touching source documents.

    Only the auxiliary rss_ingest_keys table is changed. Existing source_documents
    and info_influence rows are never deleted or updated by this migration.
    """
    cleared = database.raw.execute(
        """UPDATE rss_ingest_keys
              SET normalized_hash=''
            WHERE normalized_hash<>''
            RETURNING id"""
    ).fetchall()
    removed_hash_only = database.raw.execute(
        """DELETE FROM rss_ingest_keys
            WHERE canonical_url=''
            RETURNING id"""
    ).fetchall()
    database.commit()
    return len(cleared), len(removed_hash_only)


def backfill_canonical_url_keys(database) -> tuple[int, int]:
    rows = database.execute(
        """SELECT id,source_id,source_url
             FROM source_documents
            WHERE source_kind='rss' AND source_id IS NOT NULL
            ORDER BY COALESCE(NULLIF(published_at,'')::timestamptz,
                              NULLIF(created_at,'')::timestamptz),id"""
    ).fetchall()
    inserted = 0
    for index, row in enumerate(rows, 1):
        url = primary_dedup.canonicalize_url(row['source_url'] or '')
        if not url:
            continue
        result = database.raw.execute(
            """INSERT INTO rss_ingest_keys(source_id,source_document_id,canonical_url,normalized_hash,created_at)
               VALUES (%s,%s,%s,'',now()) ON CONFLICT DO NOTHING RETURNING id""",
            (int(row['source_id']), int(row['id']), url),
        ).fetchone()
        if result:
            inserted += 1
        if index % 1000 == 0:
            database.commit()
    database.commit()
    total = database.raw.execute(
        "SELECT count(*) FROM rss_ingest_keys WHERE canonical_url<>''"
    ).fetchone()[0]
    return inserted, int(total or 0)


def main():
    database = connect()
    try:
        database.raw.execute(SQL)
        database.commit()
        cleared, removed_hash_only = sanitize_legacy_ingest_keys(database)
        inserted, total = backfill_canonical_url_keys(database)
        print('V63_SAFE_RSS_SCHEMA_OK')
        print(f'V63_LEGACY_HASH_VALUES_CLEARED={cleared}')
        print(f'V63_HASH_ONLY_SERVICE_KEYS_REMOVED={removed_hash_only}')
        print(f'V63_CANONICAL_URL_KEYS_ADDED={inserted}')
        print(f'V63_CANONICAL_URL_KEYS_TOTAL={total}')
    finally:
        database.close()


if __name__ == '__main__':
    main()
